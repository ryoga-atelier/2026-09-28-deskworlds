import assert from 'node:assert/strict';
import {register} from 'node:module';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {readFileSync,existsSync} from 'node:fs';
const root=pathToFileURL(resolve(process.argv[2])+'/');
register(new URL('scenes/riverscape/tests/three-loader.mjs',root));
const THREE=await import(new URL('vendor/three.module.js',root));
const src=new URL('scenes/riverscape/src/',root);
const {createFrameMetrics}=await import(new URL('frame-metrics.js',src));
const metrics=createFrameMetrics(120);
for(let i=0;i<61;i++)metrics.record(1000+i*1000/30);
assert.ok(Math.abs(metrics.stats().fpsMeasured-30)<0.001);
const stable=metrics.stats();assert.deepEqual(metrics.stats(),stable,'Reading stats must not animate or alter timing');
metrics.record(10000);assert.equal(metrics.stats().samples,0,'A suspended gap must not masquerade as active frame time');
assert.equal(metrics.stats().fpsMeasured,null);
for(let i=1;i<181;i++)metrics.record(10000+i*1000/30);
assert.equal(metrics.stats().samples,120,'Timing history remains bounded');
const {createAquariumDetails}=await import(new URL('aquarium-details.js',src));
const scene=new THREE.Scene(),aquarium=createAquariumDetails(scene);
const version=aquarium.surface.geometry.attributes.position.version;
for(let t=0;t<10;t+=1/60)aquarium.update(t);
assert.equal(aquarium.surface.geometry.attributes.position.version,version,'Surface waves must not reupload CPU geometry');
const shader={uniforms:{},vertexShader:THREE.ShaderLib.physical.vertexShader};
aquarium.surface.material.onBeforeCompile(shader);
assert.doesNotMatch(shader.vertexShader,/--\d/,'Negative world coordinates must not emit GLSL decrement tokens');
assert.ok(shader.uniforms.waterTime);
for(const name of ['Submerged filter pump and strainer','Aquarium filter return','Filter outflow lip','Filter suction cup on rear pane'])assert.ok(scene.getObjectByName(name),'Connected circulation assembly retains '+name);
const {ROCKS,rockCenterY}=await import(new URL('environment.js',src));
const {groundHeight}=await import(new URL('math.js',src));
const {woodPoint,tuneRock,rockPoint}=await import(new URL('aquascape-layout.js',src));
assert.ok(ROCKS[1].ry/ROCKS[0].ry<0.75,'Stones must not remain mirrored in height');
for(const rock of ROCKS){assert.ok(rockCenterY(rock)-rock.ry < groundHeight(rock.x,rock.z),'Every stone remains partly buried');}
const base=woodPoint(3.48,.37,-.15);assert.ok(Math.abs(base.y-groundHeight(base.x,base.z))<.16);
const sourceRock={x:-4.7,z:-.35,rx:1.35,ry:1.45,rz:1,lean:-.12};
const next=tuneRock(sourceRock,1),oldCentre=groundHeight(sourceRock.x,sourceRock.z)+sourceRock.ry*.57-Math.abs(sourceRock.lean)*sourceRock.rx*.55;
const attached=rockPoint(1,sourceRock.x,oldCentre,sourceRock.z);
assert.ok(attached.distanceTo(new THREE.Vector3(next.x,rockCenterY(next),next.z))<1e-7,'Attached growth uses the grounded stone transform');
const {makeAnatomy}=await import(new URL('fish-anatomy.js',src));const mesh=makeAnatomy().body;
const p=mesh.attributes.position,parts=mesh.attributes.aPart;let min=Infinity,max=-Infinity;
for(let i=0;i<p.count;i++)if(parts.getX(i)===0){min=Math.min(min,p.getY(i));max=Math.max(max,p.getY(i));}
assert.ok((max-min)/.645<.23,'Male guppy torso is slender relative to standard length');
assert.equal(existsSync(new URL('shrimp.js',src)),false);
assert.equal(JSON.parse(readFileSync(new URL('guppy-customization.json',root))).revision,'natural-guppy-v7');
console.log('PASS: passive actual-frame timing, bounded history, GPU surface waves, negative-coordinate GLSL, connected filter, grounded asymmetric hardscape/attachments, slender guppy torso and no shrimp');
